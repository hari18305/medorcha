"""Demonstrate weight recalibration end to end with SIMULATED clinician reviews.

WHAT THIS IS: a demonstration that the recalibration *mechanism* works -- reviews
go into the review table, ``recalibrate_weights()`` reads them, the weights move,
and ``compute_confidence`` then uses the new weights.

WHAT THIS IS NOT: evidence that recalibration improves anything. Only 3 real
clinician reviews exist (10 are needed). This script pads them with 7 reviews
written by the developer, labelled ``SIMULATED-developer``. Their accept/override
outcomes are generated by a rule chosen below, so the fitted weights simply
reflect that rule. Do NOT quote the resulting weights as learned from clinicians.

Safety: everything happens in a throwaway SQLite file. The real database and the
real weight history are only READ (to copy the 3 genuine reviews) and never written.

    python scripts/demo_recalibration_simulated.py
"""

import os
import random
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from backend.models.schemas import CaseInput, FinalReport, Patient  # noqa: E402
from backend.services import storage  # noqa: E402
from backend.services.confidence import get_current_weights  # noqa: E402
from backend.services.weight_tuner import (  # noqa: E402
    DEFAULT_MIN_REVIEWS,
    collect_review_outcomes,
    recalibrate_weights,
)

SEED = 7
N_SIMULATED = 7
SIMULATED_REVIEWER = "SIMULATED-developer"

BANNER = """
==============================================================================
 SIMULATED DEMONSTRATION -- NOT CLINICAL EVIDENCE
 {real} real clinician review(s) + {sim} simulated review(s) written by the
 developer. Outcomes of the simulated ones follow a rule chosen in this script
 (agreement-driven), so the fitted weights only reflect that rule.
==============================================================================
"""


def _simulated_rows(rng: random.Random, n: int) -> list[dict]:
    """Seeded fake confidence breakdowns. The simulated 'reviewer' accepts when
    the agreement signal is high -- an assumption, stated here, not a finding."""
    rows = []
    for i in range(n):
        s_rag, s_web, agreement = rng.uniform(0.2, 0.9), rng.uniform(0.2, 0.9), rng.uniform(0.2, 0.9)
        rows.append(
            {
                "case_id": f"SIMULATED_{i + 1:02d}",
                "s_rag": s_rag,
                "s_web": s_web,
                "agreement": agreement,
                "decision": "accept" if agreement >= 0.55 else "override",
            }
        )
    return rows


def main() -> None:
    # 1. READ the genuine reviews from the real database (read-only).
    real = collect_review_outcomes()
    real_weights = dict(get_current_weights())

    # 2. Everything from here on happens in a throwaway database.
    original_db_path = storage.DB_PATH
    tmp = tempfile.NamedTemporaryFile(suffix=".db", delete=False)
    tmp.close()
    try:
        storage.DB_PATH = tmp.name
        storage._init_tables()

        def _store(case_id: str, s_rag: float, s_web: float, agreement: float, decision: str, reviewer: str) -> None:
            w = get_current_weights()
            confidence = w["w1"] * s_rag + w["w2"] * s_web + w["w3"] * agreement
            storage.save_case(CaseInput(case_id=case_id, patient=Patient(age=50, sex="female")), status="completed")
            storage.save_report(
                case_id,
                FinalReport(case_id=case_id, diagnoses=[], confidence=confidence, evidence=[], review_required=False),
                confidence_breakdown={
                    "s_rag": s_rag, "s_web": s_web, "agreement": agreement, "confidence": confidence,
                },
            )
            storage.save_review(case_id, {"decision": decision, "annotation": None, "reviewer": reviewer})

        for row in real:
            _store(row["case_id"], row["s_rag"], row["s_web"], row["agreement"],
                   "accept" if row["outcome"] == 1.0 else "override", "real-clinician (copied)")

        needed = max(0, DEFAULT_MIN_REVIEWS - len(real))
        for row in _simulated_rows(random.Random(SEED), max(N_SIMULATED, needed)):
            _store(row["case_id"], row["s_rag"], row["s_web"], row["agreement"], row["decision"], SIMULATED_REVIEWER)

        n_real, n_total = len(real), len(collect_review_outcomes())
        print(BANNER.format(real=n_real, sim=n_total - n_real))

        before = dict(get_current_weights())
        result = recalibrate_weights()
        after = dict(get_current_weights())

        print(f"reviews used : {n_total} ({n_real} real, {n_total - n_real} simulated)")
        print(f"before       : w1={before['w1']:.3f}  w2={before['w2']:.3f}  w3={before['w3']:.3f}")
        if result is None:
            print("after        : (recalibration did not run)")
        else:
            print(f"after        : w1={after['w1']:.3f}  w2={after['w2']:.3f}  w3={after['w3']:.3f}")
        print("\n(w1 = RAG, w2 = live web evidence, w3 = agreement; threshold 0.65 unchanged.)")
        print("Real weights in the real database were NOT changed.")
    finally:
        storage.DB_PATH = original_db_path
        Path(tmp.name).unlink(missing_ok=True)

    assert dict(get_current_weights()) == real_weights, "real weights changed -- this must never happen"


if __name__ == "__main__":
    os.environ.setdefault("LLM_PROVIDER", "anthropic")  # no LLM is called; avoids provider checks
    main()
